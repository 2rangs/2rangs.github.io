강아지풀의 살랑 지수는 평균 4.2로, 대조군인 일반 잡초(1.1)보다 개의 꼬리(4.5)에 훨씬 가까웠다. 이는 강아지풀이 식물보다는 꼬리처럼 흔들린다는 것을 뜻한다. 저자는 이 차이를 처음 확인한 날 길가에서 오래 서 있었다.

### 4.3 행동 실험

실험견 7마리 가운데 6마리(85.7%)가 강아지풀에 가장 먼저 다가갔다. 고무 장난감에 먼저 다가간 개는 없었다.

