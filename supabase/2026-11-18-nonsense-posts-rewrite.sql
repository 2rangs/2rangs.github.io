## 초록

**배경** 인간의 꼬리는 진화 과정에서 퇴화했다고 알려져 있다. 그러나 기존 연구는 꼬리가 *어떻게* 사라졌는지만 설명할 뿐, *어디로* 갔는지는 설명하지 않는다.

**방법** 서울 시내 산책로 세 곳에서 강아지풀(*Setaria viridis*) 312개체를 관찰하고, 형태 지표와 바람에 대한 흔들림 정도(살랑 지수)를 측정했다. 반려견 7마리를 대상으로 선호도 실험도 진행했다.

**결과** 강아지풀은 인간 꼬리의 추정 형질 5개 가운데 4개와 일치했다. 나머지 1개(위치)는 이동한 것으로 해석했다. 실험견의 85.7%가 강아지풀에 가장 먼저 다가갔다.

**결론** 강아지풀은 인간의 꼬리다. 엄연한 사실이다.

**주제어** 강아지풀, 꼬리, 미추, 식물화, 구미초(狗尾草), 그런 느낌

## 1. 서론

인류의 조상은 약 2,500만 년 전 꼬리를 잃었다. 꼬리가 있던 자리에는 꼬리뼈(미추)라는 흔적만 남았고, 교과서는 이것으로 이야기를 끝낸다.

그러나 질량 보존 법칙에 따르면 물질은 사라지지 않는다. 꼬리가 몸에서 사라졌다면, 그 꼬리는 어딘가에 있어야 한다. 학계는 지난 150년 동안 이 질문을 외면해 왔다.

![꼬리가 그냥 사라졌다고요? 강아지풀입니다](/img/posts/foxtail-is-human-tail/01-ancient-aliens.webp)
*그림 1. 본 연구의 출발점이 된 문제의식.*

본 연구는 이 질문에 답하기 위해 **인간 꼬리 식물화 가설**(Hominid Caudal Phytomorphosis Hypothesis, 이하 HCPH)을 제안한다. 요지는 간단하다. 퇴화한 꼬리 가운데 일부는 몸에서 떨어져 나간 뒤에도 분해되지 않았고, 땅에 뿌리를 내려 오늘날의 강아지풀이 되었다.

## 2. 선행 연구

꼬리 상실의 유전적 기제는 최근에야 밝혀졌다. Xia 등(2024)은 TBXT 유전자에 끼어든 짧은 서열 하나가 유인원의 꼬리를 없앴다고 보고했다. 꼬리가 *어떻게* 사라졌는지에 대한 훌륭한 설명이다. 다만 이 논문 역시 꼬리가 *어디로* 갔는지는 다루지 않는다.

반면 동아시아 문헌은 이 문제에 훨씬 일찍 접근했다. 강아지풀의 한자 이름은 구미초(狗尾草), 곧 '개의 꼬리 풀'이다. 옛사람들은 이 풀이 꼬리라는 사실을 정확히 알고 있었다. 누구의 꼬리인지 적지 않았을 뿐이다. 본 연구진은 이를 '기록상의 누락'으로 본다.

본 연구진은 반대 견해도 성실하게 검토했다.

![진실의 두루마리: 강아지풀은 벼과 한해살이풀이다](/img/posts/foxtail-is-human-tail/02-scroll-of-truth.webp)
*그림 2. 반대 견해에 대한 본 연구진의 검토 과정.*

## 3. 연구 방법

### 3.1 표본

2025년 2월, 서울 시내 산책로 세 곳에서 강아지풀 312개체를 관찰했다. 채집은 하지 않았다. 누군가의 꼬리일 수 있는 것을 함부로 뽑을 수는 없기 때문이다. 이 결정은 본 연구의 연구 윤리 원칙에 따랐다(저자 단독 심의, 승인 번호 없음).

### 3.2 형태 측정

각 개체의 이삭 길이, 잔털 밀도, 휘어짐 정도를 눈으로 측정했다. 바람에 대한 반응은 다음과 같이 정의한 **살랑 지수**(Wag Index, WI)로 수치화했다.

> WI = 1분간 흔들린 횟수 ÷ 체감 풍속

체감 풍속은 저자의 머리카락이 날리는 정도로 판정했다.

### 3.3 행동 실험

동네 반려견 7마리에게 강아지풀, 일반 잡초, 고무 장난감을 같은 거리에 두고 무엇에 가장 먼저 다가가는지 기록했다. 보호자 동의는 산책 중 구두로 받았다.

### 3.4 통계 분석

결과가 가설을 지지하는 방향으로 나올 때까지 분석했다. 유의 수준은 p < 0.05로 잡았고, 필요할 때마다 조금씩 조정했다.

