## 3. 위장 분석: 맥그로 효과

이 사건에서 가장 주목할 점은 대상의 위장이다. 대상은 범행 때마다 **빨간 고무장갑을 머리에 썼다.** 장갑의 손가락 부분이 닭 볏처럼 보였고, 수배 전단 속 범인은 닭이 되었다.

본 팀은 이처럼 머리 위 소품 하나만으로 관찰자가 대상을 전혀 다른 종으로 인식하는 현상을 **맥그로 효과**(McGraw Effect)라고 부른다.

| 관찰자 | 닭으로 인식한 비율 |
|---|---|
| 수배 전단을 본 시민 | 100% |
| 월레스 | 해당 없음 (애초에 의심하지 않음) |
| 그로밋 | 0% |

![가면을 벗기니 닭이 아니라 펭귄이었다](/img/posts/do-you-know-this-chicken/04-scooby-reveal.webp)
*그림 4. 그로밋에 의한 신원 확인 과정.*

위장의 핵심은 정교함이 아니라 **기대**에 있다. 사람들은 수배 전단에서 닭을 보았고, 그래서 닭을 찾았다. 펭귄은 찾지 않았다. 대상은 이 틈을 이용했다.

![쟤들은 내가 닭이 아니라는 걸 모르겠지](/img/posts/do-you-know-this-chicken/05-they-dont-know.webp)
*그림 5. 위장 중인 대상의 심리 상태 추정도.*

## 4. 그로밋의 수사

그로밋은 집을 떠났지만 수사를 그만두지 않았다. 주목할 기법은 다음과 같다.

- **이상 징후 기록** 방이 바뀌고, 음악이 커지고, 월레스가 달라졌다. 그로밋은 이 변화를 하나의 사건으로 묶어 보았다.
- **잠복** 집 밖에서 대상의 움직임을 계속 지켜보았다.
- **결정적 장면 포착** 대상이 고무장갑을 머리에 쓰는 순간을 직접 목격했다. 수배 전단의 '닭'과 집 안의 펭귄이 하나로 이어진 순간이다.

