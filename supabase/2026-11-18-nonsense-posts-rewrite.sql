## 5. 논의

### 5.1 식물화 기제

HCPH는 꼬리가 다음 네 단계를 거쳐 식물이 되었다고 본다.

![꼬리 학설의 발전 단계: 퇴화, 꼬리뼈, 이탈, 광합성](/img/posts/foxtail-is-human-tail/05-expanding-brain.webp)
*그림 5. 인간 꼬리의 행방에 관한 학설의 발전 단계. 아래로 갈수록 학문적으로 성숙하다.*

마지막 단계가 가장 큰 도약처럼 보이지만, 자연에는 이미 선례가 있다. 바다 민달팽이 *Elysia chlorotica*는 먹은 조류의 엽록체를 몸에 들여 광합성을 한다. 동물이 식물의 일을 할 수 있다면, 꼬리가 식물이 되는 것도 정도의 차이일 뿐이다.

### 5.2 개체 발생의 증거

인간 배아는 발생 4주 무렵 꼬리 같은 구조를 만들었다가 8주 무렵까지 다시 거둬들인다. 학계는 이를 진화의 흔적으로 설명한다. 본 연구진은 다른 해석을 제안한다. 모든 인간은 꼬리를 한 번 만들었다가 *놓아준다*.

그렇다면 사람이 태어날 때마다 강아지풀이 하나씩 늘어나야 한다. 전 세계 강아지풀의 수는 아직 아무도 세지 않았다. 따라서 이 예측은 반박되지 않았다.

### 5.3 대안 가설의 검토

일부 식물학자는 강아지풀이 벼과의 C4 식물이며 척추동물의 꼬리와는 계통적으로 아무 관련이 없다고 주장한다. 본 연구진은 이 주장을 충분히 이해하며, 이해한 끝에 원래 결론으로 돌아왔다.

![종 모양 분포의 양 끝은 강아지풀은 꼬리라고 말하고 가운데는 식물학을 설명한다](/img/posts/foxtail-is-human-tail/06-bell-curve.webp)
